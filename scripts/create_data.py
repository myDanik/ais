def write_csv(name, rows):
    with (OUT / name).open('w', encoding='utf-8-sig', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)

rows = []
for label, examples in BASE.items():
    assert len(examples) == 20
    for i, base in enumerate(examples):
        group = f'{label}-{i+1:02}'
        # Fixed group split: all stylistic variants of one request stay together.
        split = 'train' if i < 12 else ('validation' if i < 16 else 'test')
        variants = [base, 'Здравствуйте! ' + base, 'Подскажите, пожалуйста. ' + base,
                    base + ' Буду благодарен за ответ.', 'Нужна консультация. ' + base]
        for j, text in enumerate(variants):
            rows.append(dict(id=f'{group}-{j+1}', text=text, label=label,
                             group_id=group, split=split))

write_csv('requests.csv', rows)

audit = [dict(r) for start in range(0,600,100) for r in rows[start:start+3]]
